CREATE DATABASE IF NOT EXISTS library_management CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE library_management;

CREATE TABLE IF NOT EXISTS books (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT,
 title VARCHAR(150) NOT NULL,
 author VARCHAR(100) NOT NULL,
 isbn VARCHAR(20) NOT NULL UNIQUE,
 category VARCHAR(80) NOT NULL,
 quantity INT UNSIGNED NOT NULL DEFAULT 0,
 available INT UNSIGNED NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (id),
 CONSTRAINT chk_books_available CHECK (available <= quantity)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS members (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT,
 full_name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 phone VARCHAR(30) NULL,
 student_code VARCHAR(40) NOT NULL UNIQUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS loans (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT,
 book_id INT UNSIGNED NOT NULL,
 member_id INT UNSIGNED NOT NULL,
 issue_date DATE NOT NULL,
 due_date DATE NOT NULL,
 return_date DATE NULL,
 status ENUM('issued','returned') NOT NULL DEFAULT 'issued',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (id),
 INDEX idx_loans_status_due (status,due_date),
 CONSTRAINT fk_loans_book FOREIGN KEY (book_id) REFERENCES books(id) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT fk_loans_member FOREIGN KEY (member_id) REFERENCES members(id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;
